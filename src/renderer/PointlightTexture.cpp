static void
DecompressDxt1(const uint8 *blocks, int w, int h, uint32 *out)
{
	const int bw = w / 4;
	const int bh = h / 4;

	for (int by = 0; by < bh; by++)
	{
		for (int bx = 0; bx < bw; bx++)
		{
			const uint8 *blk = blocks + (by * bw + bx) * 8;
			const uint16 c0 = (uint16)(blk[0] | (blk[1] << 8));
			const uint16 c1 = (uint16)(blk[2] | (blk[3] << 8));
			const uint32 bits = (uint32)blk[4] | ((uint32)blk[5] << 8) |
			                    ((uint32)blk[6] << 16) | ((uint32)blk[7] << 24);

			uint32 pal[4];
			const uint32 r0 = ((c0 >> 11) & 0x1F) * 255 / 31;
			const uint32 g0 = ((c0 >> 5) & 0x3F) * 255 / 63;
			const uint32 b0 = (c0 & 0x1F) * 255 / 31;
			const uint32 r1 = ((c1 >> 11) & 0x1F) * 255 / 31;
			const uint32 g1 = ((c1 >> 5) & 0x3F) * 255 / 63;
			const uint32 b1 = (c1 & 0x1F) * 255 / 31;

			if (c0 > c1)
			{
				pal[0] = (0xFF << 24) | (b0 << 16) | (g0 << 8) | r0;
				pal[1] = (0xFF << 24) | (b1 << 16) | (g1 << 8) | r1;
				pal[2] = (0xFF << 24) | (((2 * b0 + b1) / 3) << 16) |
				         (((2 * g0 + g1) / 3) << 8) | ((2 * r0 + r1) / 3);
				pal[3] = (0xFF << 24) | (((b0 + 2 * b1) / 3) << 16) |
				         (((g0 + 2 * g1) / 3) << 8) | ((r0 + 2 * r1) / 3);
			}
			else
			{
				pal[0] = (0xFF << 24) | (b0 << 16) | (g0 << 8) | r0;
				pal[1] = (0xFF << 24) | (b1 << 16) | (g1 << 8) | r1;
				pal[2] = (0xFF << 24) | (((b0 + b1) / 2) << 16) |
				         (((g0 + g1) / 2) << 8) | ((r0 + r1) / 2);
				pal[3] = 0xFF000000;
			}

			for (int py = 0; py < 4; py++)
			{
				for (int pxi = 0; pxi < 4; pxi++)
				{
					const uint32 idx = (bits >> (2 * (4 * py + pxi))) & 3;
					out[(by * 4 + py) * w + bx * 4 + pxi] = pal[idx];
				}
			}
		}
	}
}

static RwTexture *
CreateTextureFromDxt1(const uint8 *blocks, int w, int h, bool invertV)
{
	RwRaster *ras = RwRasterCreate(w, h, 32, rwRASTERTYPETEXTURE | rwRASTERFORMAT8888);
	if (!ras)
		return nil;
	RwUInt32 *pixels = (RwUInt32 *)RwRasterLock(ras, 0, rwRASTERLOCKWRITE);
	if (pixels) {
		DecompressDxt1(blocks, w, h, pixels);
		if (invertV) {
			RwUInt32 *row = (RwUInt32 *)rwMalloc(sizeof(RwUInt32) * w, rw::MEMDUR_FUNCTION);
			if (row) {
				for (int y = 0; y < h / 2; y++) {
					RwUInt32 *arriba = &pixels[y * w];
					RwUInt32 *abajo = &pixels[(h - 1 - y) * w];
					memcpy(row, arriba, sizeof(RwUInt32) * w);
					memcpy(arriba, abajo, sizeof(RwUInt32) * w);
					memcpy(abajo, row, sizeof(RwUInt32) * w);
				}
				rwFree(row);
			}
		}
		RwRasterUnlock(ras);
	}
	return RwTextureCreate(ras);
}

